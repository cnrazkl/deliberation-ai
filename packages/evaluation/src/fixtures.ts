const probabilitiesFor = (label: EvaluationLabel): Record<EvaluationLabel, number> =>
  Object.fromEntries(
    evaluationLabels.map((candidate) => [candidate, candidate === label ? 0.85 : 0.05]),
  ) as Record<EvaluationLabel, number>;

export function buildPerfectFixturePredictions(
  split: "development" | "held_out" = "held_out",
): EvaluationPrediction[] {
  return offlineFixtureCorpus.items
    .filter((item) => item.split === split)
    .map((item) => ({
      itemId: item.id,
      status: "assessed" as const,
      label: item.goldLabel,
      probabilities: probabilitiesFor(item.goldLabel),
    }));
}
